const CMA_PUBLISHER = "The Cleveland Museum of Art";
const AIC_PUBLISHER = "The Art Institute of Chicago";
const MET_PUBLISHER = "The Metropolitan Museum of Art";

const cmaId = (acc: string) => `SRC-CMA-${acc.replace(/\./g, "-")}`;
const aicId = (acc: string) => `SRC-AIC-${acc.replace(/\./g, "-")}`;

const cmaSource = (acc: string, title: string): Source => ({
  id: cmaId(acc),
  type: "museum",
  title: `${title} — collection record ${acc}`,
  publisher: CMA_PUBLISHER,
  url: `https://clevelandart.org/art/${acc}`,
  rightsNote: "Record, catalogue text and photograph released by the museum as CC0 (Open Access).",
  isFixture: false,
});

const aicSource = (recordId: number, acc: string, title: string): Source => ({
  id: aicId(acc),
  type: "museum",
  title: `${title} — collection record ${acc}`,
  publisher: AIC_PUBLISHER,
  url: `https://www.artic.edu/artworks/${recordId}`,
  rightsNote: "Photograph released by the museum as CC0 (public domain). Descriptive text not reused.",
  isFixture: false,
});

const metId = (acc: string) => `SRC-MET-${acc.replace(/\./g, "-")}`;

const metSource = (objectId: number, acc: string, title: string): Source => ({
  id: metId(acc),
  type: "museum",
  title: `${title} — collection record ${acc}`,
  publisher: MET_PUBLISHER,
  url: `https://www.metmuseum.org/art/collection/search/${objectId}`,
  rightsNote: "Record data and photograph released by the museum as CC0 (Open Access). No catalogue text reused.",
  isFixture: false,
});

const metRef = (objectId: number, acc: string, creditLine: string): ReferenceHolding => ({
  institution: MET_PUBLISHER,
  accessionNumber: acc,
  url: `https://www.metmuseum.org/art/collection/search/${objectId}`,
  licence: "CC0",
  creditLine,
});


/** Concave bracket from the stem (vertical tangent) to the serif (horizontal tangent). */
const bracket = ([sx, sy], [ex, ey], steps = 8) =>
  range(0, 90, 90 / steps).map((deg) => {
    const t = (deg * Math.PI) / 180;
    return [ex + (sx - ex) * Math.cos(t), sy + (ey - sy) * Math.sin(t)];
  });
